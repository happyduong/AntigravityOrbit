public struct L10n {
    public static func tr(_ key: String, _ args: CVarArg...) -> String {
        let mgr = LocalizationManager.shared
        if args.isEmpty {
            return mgr.tr(key)
        }
        let format = mgr.tr(key)
        let langCode = mgr.currentLanguage.rawValue
        return String(format: format, locale: Locale(identifier: langCode), arguments: args)
    }
}
