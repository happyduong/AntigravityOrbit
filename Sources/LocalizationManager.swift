extension Notification.Name {
    public static let languageDidChange = Notification.Name("AntigravityOrbitLanguageDidChange")
}

public class LocalizationManager {
    public static let shared = LocalizationManager()

    public private(set) var currentLanguage: AppLanguage = .vi

    private init() {
        let saved = ConfigManager.shared.config.language
        self.currentLanguage = AppLanguage(rawValue: saved) ?? .vi
    }

    public func setLanguage(_ language: AppLanguage) {
        guard language != currentLanguage else { return }
        currentLanguage = language
        ConfigManager.shared.updateLanguage(language.rawValue)
        NotificationCenter.default.post(name: .languageDidChange, object: language)
    }

    public func tr(_ key: String, _ args: CVarArg...) -> String {
        let langCode = currentLanguage.rawValue
        var formatString = translations[langCode]?[key]
        if formatString == nil {
            formatString = translations["vi"]?[key] ?? translations["en"]?[key] ?? key
        }
        guard let format = formatString else { return key }
        if args.isEmpty {
            return format
        }
        return String(format: format, locale: Locale(identifier: langCode), arguments: args)
    }

